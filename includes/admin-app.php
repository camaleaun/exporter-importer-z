<?php
/**
 * The Export screen: an admin page built with @wordpress/build (routes/ →
 * build/), booted by core's @wordpress/boot, with DataViews and DataForm,
 * running the plugin's abilities. In Settings → General:
 *
 * - "Replace Tools → Export" (on by default): Tools → Export opens it,
 *   unless "Use the classic Export screen" is on — then Tools → Export is
 *   WordPress's screen with the plugin's choices added (also at
 *   export.php?classic=1).
 * - Off: WordPress's Export screen is left as it is, and this one is
 *   Tools → Eizport.
 *
 * @package Eizport
 */

namespace Eizport\AdminApp;

defined( 'ABSPATH' ) || exit;

const SLUG = 'eizport-export-wp-admin';

/**
 * The page's render callback, generated by @wordpress/build.
 */
const RENDER = 'eizport_eizport_export_wp_admin_render_page';

/**
 * Registers the hooks, when the screen was built.
 */
function bootstrap() {
	$build = dirname( __DIR__ ) . '/build/build.php';
	if ( ! is_file( $build ) ) {
		return;
	}
	require_once $build;

	add_action( 'admin_menu', __NAMESPACE__ . '\add_page' );
	add_action( 'load-export.php', __NAMESPACE__ . '\redirect' );
	add_action( 'admin_enqueue_scripts', __NAMESPACE__ . '\add_script_translations' );
}

/**
 * The file of the @wordpress/boot module asset the site provides: the
 * Gutenberg plugin's when active (it replaces core's module), else core's
 * (WordPress 7.0+).
 *
 * @return string Path, or '' when there is none.
 */
function boot_asset_file() {
	$files = array( ABSPATH . WPINC . '/js/dist/script-modules/boot/index.min.asset.php' );
	if ( defined( 'GUTENBERG_VERSION' ) ) {
		array_unshift( $files, WP_PLUGIN_DIR . '/gutenberg/build/modules/boot/index.min.asset.php' );
	}
	foreach ( $files as $file ) {
		if ( is_file( $file ) ) {
			return $file;
		}
	}

	return '';
}

/**
 * The @wordpress/boot asset (dependencies, version), for the page generated
 * by @wordpress/build (build/modules/boot/index.min.asset.php returns it).
 *
 * @return array{dependencies: string[], version: string|false}
 */
function boot_asset() {
	$file  = boot_asset_file();
	$asset = '' === $file ? null : require $file;

	return is_array( $asset ) ? $asset : array(
		'dependencies' => array(),
		'version'      => false,
	);
}

/**
 * Whether the screen can run: it was built (WordPress 7.0+ has
 *
 * @wordpress/boot).
 *
 * @return bool
 */
function available() {
	return function_exists( RENDER );
}

/**
 * Whether Tools → Export is the plugin's (the new screen, or the classic
 * one with the plugin's choices), as "Replace Tools → Export" asks. Off,
 * WordPress's Export screen gets nothing from the plugin.
 *
 * @return bool
 */
function replaces_export() {
	return \Eizport\Settings\get()['replace_export'];
}

/**
 * Whether Tools → Export is the classic screen ("Use the classic Export
 * screen"), which only applies while Tools → Export is replaced.
 *
 * @return bool
 */
function extends_core_screen() {
	$settings = \Eizport\Settings\get();

	return $settings['replace_export'] && $settings['classic_ui'];
}

/**
 * Whether the new screen is on and can run: in place of Tools → Export (the
 * default), or as its own Tools item when Tools → Export isn't replaced.
 *
 * @return bool
 */
function enabled() {
	return ! extends_core_screen() && available();
}

/**
 * The screen's URL, on a route.
 *
 * @param string $path Route, like "/export".
 * @return string
 */
function url( $path = '/export' ) {
	return add_query_arg(
		array(
			'page' => SLUG,
			'p'    => rawurlencode( $path ),
		),
		admin_url( 'tools.php' )
	);
}

/**
 * The screen takes the place of core's Tools → Export menu item, so the
 * admin menu highlights it as usual, and export.php links redirect to it.
 * When Tools → Export isn't replaced, it is Tools → Eizport,
 * right below Export.
 */
function add_page() {
	if ( ! enabled() ) {
		return;
	}
	// add_submenu_page() takes the item's place in the list (0, 1, 2…), not core's key (15).
	$position = null;
	foreach ( array_values( $GLOBALS['submenu']['tools.php'] ?? array() ) as $place => $item ) {
		if ( 'export.php' === $item[2] ) {
			$position = $place;
		}
	}
	if ( ! replaces_export() ) {
		$title = __( 'Eizport', 'eizport' );
		add_submenu_page( 'tools.php', $title, $title, 'export', SLUG, RENDER, null === $position ? null : $position + 1 );
		return;
	}
	remove_submenu_page( 'tools.php', 'export.php' );
	add_submenu_page( 'tools.php', __( 'Export', 'eizport' ), __( 'Export', 'eizport' ), 'export', SLUG, RENDER, $position );
}

/**
 * Tools → Export opens the new screen, when it replaces it, unless it is a
 * download or the classic screen is asked for.
 */
function redirect() {
	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- only picks the screen.
	if ( ! enabled() || ! replaces_export() || isset( $_GET['download'] ) || isset( $_GET['classic'] ) ) {
		return;
	}
	wp_safe_redirect( url() );
	exit;
}

/**
 * The plugin's translations as wp.i18n locale data: the loaded .mo (with
 * every string, the screens' too) plus the JavaScript strings of a
 * WordPress.org language pack, which keeps them in JSON files.
 *
 * @return array<string, mixed> Empty when there is nothing translated.
 */
function locale_data() {
	$domain       = 'eizport';
	$translations = get_translations_for_domain( $domain );
	$messages     = array();
	foreach ( $translations->entries as $entry ) {
		if ( array() !== array_filter( $entry->translations ) ) {
			$messages[ ( $entry->context ? $entry->context . "\4" : '' ) . $entry->singular ] = $entry->translations;
		}
	}
	$files = glob( WP_LANG_DIR . '/plugins/' . $domain . '-' . determine_locale() . '-*.json' );
	foreach ( $files ? $files : array() as $file ) {
		$json      = wp_json_file_decode( $file, array( 'associative' => true ) );
		$messages += $json['locale_data'][ $domain ] ?? $json['locale_data']['messages'] ?? array();
	}
	unset( $messages[''] );
	if ( array() === $messages ) {
		return array();
	}
	$messages[''] = array(
		'domain'       => $domain,
		'lang'         => determine_locale(),
		'plural-forms' => $translations->headers['Plural-Forms'] ?? 'nplurals=2; plural=(n != 1);',
	);

	return $messages;
}

/**
 * The new screens are script modules using the global wp.i18n, which only
 * has core's strings: on their pages, give it this plugin's translations.
 *
 * @param string $hook_suffix The admin page.
 */
function add_script_translations( $hook_suffix ) {
	unset( $hook_suffix );
	// phpcs:ignore WordPress.Security.NonceVerification.Recommended -- only picks the screen.
	$page = isset( $_GET['page'] ) ? sanitize_key( wp_unslash( $_GET['page'] ) ) : '';
	if ( ! in_array( $page, array( SLUG, \Eizport\Settings\SLUG ), true ) ) {
		return;
	}
	$data = locale_data();
	if ( array() !== $data ) {
		wp_add_inline_script( 'wp-i18n', sprintf( 'wp.i18n.setLocaleData( %s, "eizport" );', wp_json_encode( $data ) ), 'after' );
	}
}
